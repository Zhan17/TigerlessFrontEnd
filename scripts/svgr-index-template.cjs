const path = require("node:path");

// Named exports with an `Icon` suffix, e.g. arrow-right-circle.tsx ->
// `export { default as ArrowRightCircleIcon } from "./arrow-right-circle";`
function toPascal(name) {
  return name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

module.exports = function indexTemplate(filePaths) {
  const lines = filePaths
    .map((entry) => (typeof entry === "string" ? entry : entry.path))
    .map((filePath) => path.basename(filePath, path.extname(filePath)))
    .sort()
    .map(
      (base) => `export { default as ${toPascal(base)}Icon } from "./${base}";`,
    );
  return `// Generated by \`npm run icons\` (SVGR). Do not edit by hand.\n${lines.join("\n")}\n`;
};
